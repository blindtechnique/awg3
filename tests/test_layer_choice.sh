# Выбор версии слоя: Enter означает «как есть», а не «поставь ещё один слой».
#
# `ask_params` спрашивает версию только на первой установке и при
# `--reconfigure` — обычный прогон уходит в ранний возврат с сохранёнными
# ответами. Но сам вопрос предлагал «обе сразу» независимо от того, что на
# сервере стоит, а без терминала диалога не было вовсе и срабатывало
# `[ -n "$AWG_VER" ] || AWG_VER=both`.
#
# Цена ошибки: на сервере, поставленном как 2.0-only, `--reconfigure` плюс
# Enter — или `--reconfigure` вообще без терминала — означал установку всего
# слоя 3.0: apt build-essential, сборка Go и amneziawg-go из исходников, два
# новых интерфейса, две подсети и два UDP-порта. Владелец при этом приходил
# сюда за новым профилем обфускации.
#
# Обратная сторона в разделе 3: на чистой установке «обе сразу» — правильное
# умолчание, и оно должно остаться. Смена версии по-прежнему делается флагом
# `--awg`, и раздел 4 сторожит, что флаг сильнее сохранённого.
#
#   bash tests/test_layer_choice.sh

fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

AP="$(sed -n '/^ask_params()/,/^}$/p' install.sh)"
if [ -z "$AP" ]; then
    echo "  ✘ не нашли ask_params в install.sh — мерить нечего"
    exit 1
fi

TTY_OK=1
VER_ANSWER=""
run_ver() {  # run_ver <строки прежнего state или ""> <CLI_VER> → печатает выбранное
    # Функция гоняется ЦЕЛИКОМ: обрезать её по середине значило бы мерить
    # собственную склейку. --preset здесь задан только чтобы пропустить диалоги
    # обфускации — на выбор версии он в этом репозитории не влияет.
    local prev="$1" cli="$2"
    local st="$WORK/install-state.env" logf="$WORK/ver.log" d="$WORK/dest"
    rm -rf "$st" "$d"; mkdir -p "$d"
    [ -n "$prev" ] && printf '%s\n' "$prev" > "$st"
    (
        set -euo pipefail
        # export, а не простое присваивание: их читает вырезанная ask_params
        # через eval, и статически этого не видно.
        export STATE="$st" DEST="$d" \
               CLI_VER="$cli" CLI_PRESET=high CLI_TEMPLATE="" CLI_FP="" \
               CLI_PRESET3="" CLI_TEMPLATE3="" \
               PLAN=0 RECONFIGURE=1 NO_BOT=1 ENDPOINT="vpn.example.org"
        log() { :; }
        err() { :; }
        has_tty() { [ "$TTY_OK" = 1 ]; }
        ask_bot() { :; }
        ask_port() { export PORT_ANSWER=0; }
        ask_yn() { return 1; }
        ask_valid() { return 1; }
        ask_pick() { printf 'УМОЛЧАНИЕ=%s\n' "$2" >&2
                     printf -v "$1" '%s' "${VER_ANSWER:-$2}"; }
        eval "$AP"
        ask_params
    ) > "$WORK/out" 2>"$logf" || { printf 'ПАДЕНИЕ\n'; sed 's/^/       /' "$logf"; return 1; }
    sed -n "s/^AWG_VER='\(.*\)'\$/\1/p" "$st"
}
asked() { sed -n 's/^УМОЛЧАНИЕ=//p' "$WORK/ver.log" | head -1; }

STATE2="AWG_PRESET='medium'
AWG_VER='2'"

# ═══════════════════════════════════════════════════════════════════════════
head_ "1. С терминалом: умолчание — то, что уже стоит"
TTY_OK=1 VER_ANSWER=""
got="$(run_ver "$STATE2" "")"
case "$(asked)" in
    1) ok "предложено «1) 2.0» — то, что на сервере" ;;
    3) bad "предложено «обе сразу»" "Enter поднимет слой 3.0 со сборкой Go и двумя портами" ;;
    *) bad "версию не спросили" "«$(asked)»; при --reconfigure вопрос обязан быть" ;;
esac
[ "$got" = 2 ] && ok "и Enter оставил 2.0" \
    || bad "Enter изменил версию на «$got»" "владелец пришёл за профилем обфускации, а не за новым слоем"

# ═══════════════════════════════════════════════════════════════════════════
head_ "2. Без терминала: берётся то, что стоит, а не «обе сразу»"
# Диалога нет вовсе, и запасной вариант решает за владельца. Молча.
TTY_OK=0 VER_ANSWER=""
got="$(run_ver "$STATE2" "")"
[ "$got" = 2 ] && ok "без терминала осталось 2.0" \
    || bad "без терминала стало «$got»" "слой 3.0 доустановится молча, без единого вопроса"

# ═══════════════════════════════════════════════════════════════════════════
head_ "3. Чистая установка: «обе сразу» — по-прежнему правильное умолчание"
TTY_OK=1 VER_ANSWER=""
got="$(run_ver "" "")"
case "$(asked)" in
    3) ok "предложено «обе сразу»" ;;
    *) bad "умолчание чистой установки изменилось" "«$(asked)»" ;;
esac
[ "$got" = both ] && ok "и новый сервер получает оба слоя" \
    || bad "новый сервер получил «$got»"

TTY_OK=0 VER_ANSWER=""
got="$(run_ver "" "")"
[ "$got" = both ] && ok "и без терминала на чистой установке тоже both" \
    || bad "без терминала чистая установка дала «$got»"

# ═══════════════════════════════════════════════════════════════════════════
head_ "4. Флаг --awg сильнее сохранённого"
# Перенос не должен превращаться в «заморозить навсегда»: сменить набор слоёв
# по-прежнему можно, и делается это именно флагом.
TTY_OK=1 VER_ANSWER=""
got="$(run_ver "$STATE2" both)"
[ "$got" = both ] && ok "--awg both перекрывает сохранённое 2" \
    || bad "--awg проигнорирован, вышло «$got»"
[ -z "$(asked)" ] && ok "и вопрос не задаётся — ответ уже дан флагом" \
    || bad "спросили, хотя флаг задан" "умолчание «$(asked)»"

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit "$fail"
