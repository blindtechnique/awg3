#!/bin/bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Домен мимикрии — приманка, а не адрес сервера.
#
# У флага `--host` два разных смысла в двух соседних местах: в install.sh это
# АДРЕС СЕРВЕРА, а у обфускатора — домен-ПРИМАНКА. Его собственный диалог
# говорит прямо: «Кастомный домен для мимикрии (напр. yandex.ru). Enter — из
# встроенного пула доступных из РФ доменов».
#
# Установщик подавал туда реальный ENDPOINT, и шаблон voip вписывал его в
# junk-пакет дословно: `OPTIONS sip:vpn.example.org SIP/2.0`. То есть пакет,
# который должен маскировать соединение, называл вслух адрес того самого узла,
# которому он адресован — до всякого хендшейка, в открытом виде и по UDP.
# У WireGuard на проводе имени нет вовсе (SNI там отсутствует), так что это не
# мимикрия, а уникальная подпись, тривиально блокируемая DPI. Бьёт ровно по
# тем, кто выбрал voip из-за агрессивного DPI.
#
# Раздел 1 доказывает, что механизм настоящий: обфускатор действительно
# вписывает переданный домен в пакет. Раздел 2 требует, чтобы установщик туда
# ничего не подавал. Первый нужен, чтобы второй нельзя было отмахнуть как
# перестраховку.
#
#   bash tests/test_mimicry_host.sh

fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

GEN=obfuscation/awg_obfuscate.py
[ -f "$GEN" ] || { echo "  ✘ нет $GEN"; exit 1; }

# ═══════════════════════════════════════════════════════════════════════════
head_ "1. Переданный домен действительно уезжает в пакет"
# Без этого раздела запрет из раздела 2 выглядел бы перестраховкой.
MARK=vpn.secret.example
HEX="$(printf '%s' "$MARK" | od -An -tx1 | tr -d ' \n')"
if ! command -v python3 >/dev/null 2>&1; then
    printf '  · нет python3 — генератор не запускался\n'
else
    out="$(python3 "$GEN" --preset medium --template voip --fp chrome \
              --mtu 1420 --host "$MARK" --format env 2>/dev/null || true)"
    if [ -z "$out" ]; then
        bad "генератор ничего не выдал" "мерить нечего"
    elif printf '%s' "$out" | tr -d '\n' | grep -qi "$HEX"; then
        ok "домен из --host лежит в junk-пакете открытым текстом (шаблон voip)"
    else
        bad "домен не найден в пакете" "механизм изменился — раздел 2 надо пересмотреть"
    fi
    # А это уже проверка соразмерности: в остальных шаблонах дословно его нет,
    # поэтому и запрет нужен не «на всякий случай», а по конкретной причине.
    o2="$(python3 "$GEN" --preset medium --template tls --fp chrome \
             --mtu 1420 --host "$MARK" --format env 2>/dev/null || true)"
    printf '%s' "$o2" | tr -d '\n' | grep -qi "$HEX" \
        && printf '  · и в шаблоне tls тоже — тем более\n' \
        || printf '  · в tls дословно не встречается (утечка именно у voip)\n'
fi

# ═══════════════════════════════════════════════════════════════════════════
head_ "2. Установщик не подаёт обфускатору адрес сервера"
CALLS="$(grep -n 'awg-obfuscation.sh' install.sh | grep -v '^\s*#' || true)"
if [ -z "$CALLS" ]; then
    bad "не нашли вызовов обфускатора в install.sh" "мерить нечего"
else
    # Блок вызова занимает несколько строк, поэтому смотрим окно вокруг каждого.
    win="$(grep -n -A3 'awg-obfuscation.sh' install.sh | grep -v '^--$' || true)"
    case "$win" in
        *'--host "$ENDPOINT"'*|*'--host "${ENDPOINT'*)
            bad "адрес сервера уходит в --host обфускатора" \
                "шаблон voip впишет его в junk-пакет дословно" ;;
        *'--host'*)
            bad "обфускатору передаётся --host" \
                "проверь, что это домен мимикрии, а не адрес сервера: $(printf '%s' "$win" | grep -- '--host')" ;;
        *)  ok "ни один вызов не передаёт --host" ;;
    esac
fi

# Обратная сторона: адрес сервера обязан по-прежнему попадать туда, где он
# нужен, — в Endpoint клиентских конфигов. Если бы правка убрала его вообще,
# раздел 2 остался бы зелёным, а продукт сломался.
if grep -q 'Endpoint = ' bin/awg-client.sh; then
    ok "и при этом Endpoint у клиентов по-прежнему пишется"
else
    bad "Endpoint у клиентов больше не пишется" "адрес потерян не там, где надо"
fi

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit "$fail"
