# Блокеры переезда датапаса 3.0 в ядро: отчёт обязан быть честным в обе стороны.
#
# Раньше этот раздел вывода был ТЕКСТОМ: скрипт печатал заученный список причин
# («открыты #215 и #3043»). Такой текст устаревает молча — и устарел: #3043
# оказалась про 3.1 и без подтверждения мейнтейнеров, а список открытых
# дефектов вырос с двух до восьми. Поэтому состояние теперь спрашивается у
# GitHub, а тексту остаётся только пересказать ответ.
#
# Отсюда три свойства, каждое из которых ломается тихо:
#
#   открыт хоть один → отчёт называет число и номера и говорит, что слой
#                      остаётся на userspace;
#   закрыты все      → отчёт НЕ выдаёт это за разрешение переезжать: решение
#                      принимается руками, после проверки на стенде;
#   данных нет       → отчёт говорит «не удалось» и молчит о готовности. Это
#                      главное: «не смогли спросить», выданное за «всё закрыто»,
#                      и есть та ложная зелень, против которой всё затевалось.
#
# Плюс защита от самострела: у неавторизованного API GitHub 60 запросов в час на
# адрес, а кнопку «Проверить обновления» в боте нажимают сколько угодно раз.
# Поэтому ответ кэшируется, и стенд проверяет, что свежий кэш обходится БЕЗ
# единого обращения к сети, а протухший — обновляется.
#
#   bash tests/test_upstream_blockers.sh

fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

SRC=bin/awg-upstream-check.sh
FETCH="$(sed -n '/^blockers_fetch()/,/^}$/p' "$SRC")"
STATE="$(sed -n '/^blockers_state()/,/^}$/p' "$SRC")"
REPORT="$(sed -n '/^kmod3_report()/,/^}$/p' "$SRC")"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

head_ "0. Функции найдены — иначе мерить нечего"
missing=""
[ -n "$FETCH" ]  || missing="$missing blockers_fetch"
[ -n "$STATE" ]  || missing="$missing blockers_state"
[ -n "$REPORT" ] || missing="$missing kmod3_report"
if [ -n "$missing" ]; then
    bad "не нашли в $SRC:$missing" "прерываю"
    printf '\n'; exit 1
fi
ok "blockers_fetch, blockers_state и kmod3_report вырезаны из настоящего файла"

# ── подставной curl ─────────────────────────────────────────────────────────
# Отдаёт настоящий по форме ответ GitHub и считает обращения: на этом счётчике
# держится проверка кэша.
S="$WORK/stub"; mkdir -p "$S"
cat > "$S/curl" <<'CURLEOF'
#!/bin/bash
url=""
for a in "$@"; do case "$a" in https://*) url="$a" ;; esac; done
n="${url##*/}"
printf 'x' >> "${STUB_CALLS:?}"
# Номера из STUB_FAIL молча недоступны — так выглядит обрыв или лимит GitHub.
case " ${STUB_FAIL:-} " in *" $n "*) exit 22 ;; esac
printf '{"number":%s,"state":"%s","state_reason":null,"title":"x"}\n' "$n" "${STUB_STATE:-open}"
CURLEOF
chmod +x "$S/curl"

run_state() {  # run_state <кэш> [STUB_STATE] [STUB_FAIL] → вывод blockers_state
    # shellcheck disable=SC2034  # переменные ниже читают вырезанные функции через eval
    ( set -uo pipefail
      PATH="$S:$PATH"
      export STUB_CALLS="$WORK/calls" STUB_STATE="${2:-open}" STUB_FAIL="${3:-}"
      KMOD_REPO=x/y
      KMOD_BLOCKERS="215 222 233"
      BLOCKERS_CACHE="$1"
      BLOCKERS_TTL=21600
      eval "$FETCH"; eval "$STATE"
      blockers_state || echo "ОТКАЗ" )
}

report() {  # report <known> <open> <total> <list> [состояние модуля]
    # shellcheck disable=SC2034  # переменные ниже читает вырезанный kmod3_report
    ( set -uo pipefail
      KMOD3_STATE="${5:-v31}"
      BLOCKERS_KNOWN="$1"; BLOCKERS_OPEN="$2"; BLOCKERS_TOTAL="$3"; BLOCKERS_LIST="$4"
      eval "$REPORT"
      kmod3_report )
}

# ═══════════════════════════════════════════════════════════════════════════
head_ "1. Открыт хоть один блокер — это сказано числом и номерами"
OUT="$(report 1 8 8 " #215 #222 #225")"
case "$OUT" in
    *"Открыто блокеров: 8 из 8"*) ok "названо, сколько из скольких" ;;
    *) bad "числа нет" "$OUT" ;;
esac
case "$OUT" in
    *"#215"*"#222"*) ok "и перечислены номера — есть что открыть и прочитать" ;;
    *) bad "номера не перечислены" "$OUT" ;;
esac
case "$OUT" in
    *"остаётся на amneziawg-go"*) ok "и сказано, что из этого следует" ;;
    *) bad "вывод не назван" "$OUT" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "2. Все закрыты — но это не разрешение переезжать"
OUT="$(report 1 0 8 "")"
case "$OUT" in
    *"0 из 8"*) ok "сказано, что открытых не осталось" ;;
    *) bad "не сказано" "$OUT" ;;
esac
case "$OUT" in
    *"НЕ команда переезжать"*) ok "и сразу оговорено, что решение принимается руками" ;;
    *) bad "зелёный свет без оговорки" \
        "владелец прочтёт это как «можно», а проверку на стенде никто не делал: $OUT" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "3. Данных нет — отчёт молчит о готовности"
# Ровно та ложная зелень, против которой всё затевалось: «не смогли спросить»
# не имеет права выглядеть как «всё закрыто».
OUT="$(report 0 0 0 "")"
case "$OUT" in
    *"проверить не удалось"*) ok "сказано прямо, что состояние неизвестно" ;;
    *) bad "молчание вместо признания" "$OUT" ;;
esac
case "$OUT" in
    *"все известные закрыты"*) bad "неизвестность выдана за «всё закрыто»" "$OUT" ;;
    *"0 из 0"*)                bad "напечатан ноль блокеров как факт" "$OUT" ;;
    *) ok "и ни слова о том, что блокеров нет" ;;
esac
case "$OUT" in
    *"остаётся на amneziawg-go"*) ok "решение при этом не меняется" ;;
    *) bad "не сказано, что решение прежнее" "$OUT" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "4. Ответ GitHub разбирается: open и closed различаются"
: > "$WORK/calls"
OUT="$(run_state "$WORK/c1" open)"
case "$OUT" in
    *"215 open"*"222 open"*) ok "открытые прочитаны как открытые" ;;
    *) bad "разбор ответа неверен" "$OUT" ;;
esac
: > "$WORK/calls"
OUT="$(run_state "$WORK/c2" closed)"
case "$OUT" in
    *"215 closed"*) ok "закрытые — как закрытые" ;;
    *) bad "closed не распознан" "$OUT" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "5. Частичный ответ не считается ответом"
# Если об одной issue узнать не удалось, а остальные закрыты, то «0 открытых»
# было бы враньём: пропущенная как раз и может быть открытой.
: > "$WORK/calls"
OUT="$(run_state "$WORK/c3" closed "222")"
case "$OUT" in
    *ОТКАЗ*) ok "неполный ответ отвергнут" ;;
    *) bad "неполный ответ принят за полный" "$OUT" ;;
esac
[ -e "$WORK/c3" ] && bad "неполный ответ всё-таки попал в кэш" "он жил бы там до протухания" \
    || ok "и в кэш не записан"

# ═══════════════════════════════════════════════════════════════════════════
head_ "6. Свежий кэш обходится без единого обращения к сети"
# У неавторизованного API GitHub 60 запросов в час на адрес. Без кэша кнопка в
# боте выбивала бы лимит, и владелец получал бы отказ ровно тогда, когда ответ
# нужен.
printf '215 open\n222 closed\n233 open\n' > "$WORK/c4"
: > "$WORK/calls"
OUT="$(run_state "$WORK/c4" open)"
CALLS="$(wc -c < "$WORK/calls" | tr -d ' ')"
[ "$CALLS" = 0 ] && ok "обращений к сети: 0" \
    || bad "к сети обратились $CALLS раз при свежем кэше" "лимит GitHub выбьется на ровном месте"
case "$OUT" in
    *"222 closed"*) ok "и отдано именно то, что лежало в кэше" ;;
    *) bad "кэш прочитан неверно" "$OUT" ;;
esac

# ═══════════════════════════════════════════════════════════════════════════
head_ "7. Протухший кэш обновляется"
printf '215 closed\n222 closed\n233 closed\n' > "$WORK/c5"
touch -d '2 days ago' "$WORK/c5" 2>/dev/null || touch -t 202001010000 "$WORK/c5"
: > "$WORK/calls"
OUT="$(run_state "$WORK/c5" open)"
CALLS="$(wc -c < "$WORK/calls" | tr -d ' ')"
[ "$CALLS" != 0 ] && ok "за свежими данными сходили ($CALLS обращений)" \
    || bad "протухший кэш отдан как есть" "состояние блокеров замерло бы навсегда"
case "$OUT" in
    *"215 open"*) ok "и кэш заменён новым ответом" ;;
    *) bad "старое значение осталось" "$OUT" ;;
esac

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit $fail
