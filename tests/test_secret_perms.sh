# Секреты не должны лежать доступными на чтение кому попало.
#
# Два места, где это решается:
#
# 1) Клиентские профили. В .conf лежит PrivateKey клиента и PresharedKey, то же
#    самое целиком повторяется в QR и в vpn://-ссылке. Здесь это давно закрыто
#    (umask 077 + chmod 600 + сам /opt/awg3 создаётся под umask 077), и раздел 1
#    сторожит, чтобы правка не откатила это незаметно: в соседнем репозитории
#    ровно этого не было, и приватные ключи всех клиентов годами лежали 0644.
#
# 2) Ключ header protection слоя 3.0 при `awg-doctor --deep`. Проверка поднимает
#    клиента в namespace и досылает параметры 3.0 через UAPI, а для этого кладёт
#    ключ в открытом виде во временный файл. Он ложился в ОБЩИЙ /tmp обычным
#    перенаправлением, то есть 0644, под предсказуемым именем doctor$$.v3, и
#    жил там всю проверку. Ключ общий для сервера и всех клиентов слоя 3.0:
#    его компрометация снимает маскировку заголовков со всего слоя, а смена
#    требует перевыпуска профиля и переимпорта у всех.
#
# Проверки структурные: полноценный стенд потребовал бы namespace, amneziawg-go
# и настоящий обмен, и мерил бы в основном сам стенд. Здесь важно другое —
# сохранились ли ровно те решения, которые закрывают доступ.
#
#   bash tests/test_secret_perms.sh

fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

# ═══════════════════════════════════════════════════════════════════════════
head_ "1. Клиентские профили закрыты"
AC="$(sed -n '/^add_client()/,/^}$/p' bin/awg-client.sh)"
if [ -z "$AC" ]; then
    bad "не нашли add_client" "мерить нечего"
else
    n_umask="$(printf '%s\n' "$AC" | grep -n 'umask 077'      | head -1 | cut -d: -f1)"
    n_conf="$( printf '%s\n' "$AC" | grep -n 'cat > "$conf"'  | head -1 | cut -d: -f1)"
    if [ -n "$n_umask" ] && [ -n "$n_conf" ] && [ "$n_umask" -lt "$n_conf" ]; then
        ok "umask 077 стоит до записи профиля"
    else
        bad "umask 077 не предшествует записи профиля" \
            "профиль родится 0644 — приватный ключ клиента прочтёт любой локальный пользователь"
    fi
    printf '%s\n' "$AC" | grep -q 'chmod 600 "$conf"' \
        && ok "и профиль закрывается явным chmod 600" \
        || bad "нет chmod 600 на профиле" "umask не спасает при перезаписи поверх существующего файла"
fi

# Каталог с профилями сам по себе 0755, и это не дыра ровно потому, что
# родительский /opt/awg3 создаётся закрытым. Если порядок здесь сломают,
# клиентские каталоги станут проходными.
IN="$(grep -n -A2 '^    umask 077$' install.sh | grep -c 'mkdir -p "\$DEST"')"
[ "$IN" -ge 1 ] \
    && ok "\$DEST создаётся уже под umask 077" \
    || bad "mkdir \$DEST не идёт следом за umask 077" \
           "каталог станет 0755, и клиентские подкаталоги окажутся проходными"

# ═══════════════════════════════════════════════════════════════════════════
head_ "2. Ключ слоя 3.0 не уезжает в общий /tmp"
DR=bin/awg-doctor.sh
if grep -q '"/tmp/\$tmp\.v3"' "$DR"; then
    bad "ключ header protection пишется в общий /tmp" \
        "0644 под предсказуемым именем на всё время проверки; там же возможна подмена по симлинку"
else
    ok "ключ не пишется в общий /tmp"
fi

grep -q ': > "\$AWG_DIR/\$tmp\.v3"; chmod 600 "\$AWG_DIR/\$tmp\.v3"' "$DR" \
    && ok "файл создаётся закрытым ДО того, как в него попадает ключ" \
    || bad "нет chmod 600 перед записью ключа" \
           "перенаправление создаёт файл под текущим umask, то есть 0644"

n_chmod="$(grep -n 'chmod 600 "\$AWG_DIR/\$tmp\.v3"' "$DR" | head -1 | cut -d: -f1)"
n_write="$(grep -n 'python3 - "\$AWG_DIR/\$tmp\.conf" > "\$AWG_DIR/\$tmp\.v3"' "$DR" | head -1 | cut -d: -f1)"
if [ -n "$n_chmod" ] && [ -n "$n_write" ] && [ "$n_chmod" -lt "$n_write" ]; then
    ok "порядок именно такой: сначала права, потом ключ"
else
    bad "chmod идёт не раньше записи" "между ними ключ успевает полежать открытым"
fi

CU="$(sed -n '/cleanup_deep()/,/^    }$/p' "$DR")"
case "$CU" in
    *'$AWG_DIR/$tmp.v3'*) ok "и файл убирается после проверки" ;;
    *) bad "файл с ключом остаётся на диске" "проверка закончилась, ключ лежит" ;;
esac

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit "$fail"
