#!/bin/bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Пины апстрима: они обязаны быть согласованы между собой.
#
# Утилиты совпадают с модулем не «версией», а КОДИРОВКОЙ атрибутов netlink.
# Модуль v3.0.20260805 объявляет WG_GENL_VERSION 3 и держит H1..H4 в политике
# как NLA_U64; утилиты 1.0 при genl-версии >= 2 клали их СТРОКОЙ, то есть
# слали строку туда, где ждут u64. Утилиты 3.0 различают < 2 → u32,
# < 3 → строка, иначе u64. Поэтому пины трёх компонентов должны идти одной
# серией, и разъехаться они не должны молча.
#
#   bash tests/test_pins.sh
fail=0
ROOT="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
cd "$ROOT" || exit 1

ok()  { printf '  ✔ %s\n' "$1"; }
bad() { printf '  ✘ %s\n' "$1"; [ $# -gt 1 ] && printf '     %s\n' "$2"; fail=1; }
head_() { printf '\n\033[1m%s\033[0m\n' "$1"; }

pin() {  # pin <имя переменной> → значение пина из install.sh
    grep -m1 "^$1=" install.sh | sed 's/.*:-\([^}]*\)}.*/\1/'
}

head_ "1. Пины идут одной серией"
TOOLS="$(pin AWG_TOOLS_REF)"
KMOD="$(pin AWG_KMOD_SRC_REF)"
GO="$(pin AWG_GO_REF)"
printf '     tools=%s  kmod=%s  go=%s\n' "$TOOLS" "$KMOD" "$GO"
for p in "$TOOLS" "$KMOD" "$GO"; do
    case "$p" in
        v3.0.*) ;;
        *) bad "пин «$p» не из серии 3.0" \
              "утилиты, модуль и датапас обязаны говорить на одной кодировке" ;;
    esac
done
[ "$fail" = 0 ] && ok "tools, kmod и go — все v3.0.*"

# 3.1 не берём сознательно: kmod #215 и amnezia-client #3043 открыты.
for p in "$TOOLS" "$KMOD" "$GO"; do
    case "$p" in
        v3.1.*) bad "пин «$p» уехал на 3.1" "см. комментарий в install.sh: #215 и #3043 открыты" ;;
    esac
done
[ "$fail" = 0 ] && ok "и ни один не уехал на 3.1"

head_ "2. Версия утилит совпадёт с пином — без вечной пересборки"
# install_tools сравнивает `awg --version` с пином. Если регексп не вытащит
# из вывода ровно строку пина, cur != ref, и утилиты будут пересобираться на
# КАЖДОМ полном прогоне — с гашением интерфейсов на ровном месте.
# Анкоримся на само присваивание, а не на подстроку «awg --version»: первое
# её вхождение в файле — комментарий, и оттуда регексп не достать.
RE="$(grep -m1 'cur="\$(awg --version' install.sh       | grep -o "grep -oE '[^']*'" | sed "s/grep -oE '//; s/'\$//")"
if [ -z "$RE" ]; then
    bad "не нашли регексп версии в install.sh" "мерить нечего"
else
    got="$(printf 'awg %s\nWireGuard-Go...\n' "$TOOLS" | grep -oE "$RE" | head -1)"
    [ "$got" = "$TOOLS" ] && ok "из «awg $TOOLS» вытаскивается ровно пин" \
        || bad "регексп даёт «$got» вместо «$TOOLS»" "утилиты будут пересобираться каждый прогон"
fi

head_ "3. Устаревшее про ветку feat/awg3 не осталось там, где речь о ключах"
# Ветки нет с июля, а 3.x-ключи с этого пина разбирают обычные утилиты.
# Упоминания в объяснении, почему слой 3.0 не в ядре, — законны и остаются.
if grep -n 'feat/awg3' bin/awg-obfuscation.sh | grep -q 'понимает\|разбирает'; then
    bad "в awg-obfuscation.sh осталось «ключи понимает feat/awg3»" "ветки нет, а ключи разбирает пин"
else
    ok "про разбор ключей на удалённую ветку больше не ссылаемся"
fi

printf '\n'
[ "$fail" = 0 ] && echo "═══ ВСЁ ЗЕЛЁНОЕ ═══" || echo "═══ ЕСТЬ ПАДЕНИЯ ═══"
exit $fail
